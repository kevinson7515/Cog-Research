"""Shared online Plan-and-Act rollout loop for trajectory ablations.

All policy-generated turns, including planning, tool calls, intermediate step
summaries, and the submitted report, remain inside the VERL response mask.  A
persistent per-rollout workspace tool enforces dependencies and exposes the
offline evidence corpus through retrieval calls. The rubric schema selects
dimension-guided report reward (Condition B) or step reward (Condition C);
rollout behavior is otherwise identical.
"""

from __future__ import annotations

import copy
import json
import os
import re
from typing import Any, Mapping
from uuid import uuid4

from cosight_rl.rewards.trajectory_reward_evaluator import (
    DIMENSION_SCHEMA_VERSION,
    rubric_schema,
    score_trajectory,
)
from verl.experimental.agent_loop.agent_loop import AgentLoopOutput
from verl.experimental.agent_loop.tool_agent_loop import AgentData, AgentState, ToolAgentLoop
from verl.experimental.agent_loop.tool_parser import ToolParser
from verl.tools.schemas import ToolResponse
from verl.tools.utils.tool_registry import initialize_tools_from_config
from verl.utils.rollout_trace import rollout_trace_op


_E6B_OPERATION_ALIASES = frozenset({"create_plan", "inspect_visual", "search_evidence", "read_workspace",
                                    "save_step", "status", "submit_report"})


class CoSightPlanActAgentLoop(ToolAgentLoop):
    """A dependency-aware Co-Sight trajectory generated by the trainable policy."""

    _cosight_initialized = False

    @classmethod
    def init_class(cls, config, tokenizer, processor, **kwargs):
        if cls._cosight_initialized:
            return
        cls._cosight_initialized = True
        cls.tokenizer = tokenizer
        cls.processor = processor
        rollout = config.actor_rollout_ref.rollout
        cls.max_user_turns = rollout.multi_turn.max_user_turns
        cls.max_assistant_turns = rollout.multi_turn.max_assistant_turns
        cls.max_parallel_calls = rollout.multi_turn.max_parallel_calls
        cls.max_tool_response_length = rollout.multi_turn.max_tool_response_length
        cls.tool_response_truncate_side = rollout.multi_turn.tool_response_truncate_side
        tool_config_path = rollout.multi_turn.tool_config_path
        tool_list = initialize_tools_from_config(tool_config_path) if tool_config_path else []
        cls.tools = {tool.name: tool for tool in tool_list}
        if "cosight_step" not in cls.tools:
            raise ValueError("CoSightPlanActAgentLoop requires the cosight_step trajectory tool.")
        cls.tool_schemas = [tool.tool_schema.model_dump(exclude_unset=True, exclude_none=True) for tool in tool_list]
        cls.tool_parser = ToolParser.get_tool_parser(rollout.multi_turn.format, tokenizer)
        cls.apply_chat_template_kwargs = config.data.get("apply_chat_template_kwargs", {})
        cls.prompt_length = rollout.prompt_length
        cls.response_length = rollout.response_length
        cls.system_prompt = tokenizer.apply_chat_template(
            [{}], add_generation_prompt=False, tokenize=True, **cls.apply_chat_template_kwargs
        )
        cls.interaction_config_file = None

    async def _persistent_call_tool(self, tool_call) -> tuple[ToolResponse, float, dict]:
        try:
            name = tool_call.name
            guided = os.getenv("COSIGHT_E6B_GUIDED") == "1"
            alias = guided and name in _E6B_OPERATION_ALIASES
            if guided and name == "serper_search":
                raise ValueError('Use cosight_step with operation "search_evidence" and a query for the frozen evidence pool.')
            tool = self.tools["cosight_step" if alias else name]
            parameters = json.loads(tool_call.arguments)
            if not isinstance(parameters, dict):
                raise ValueError("tool arguments must decode to an object")
            if alias:
                if parameters.get("operation", name) != name:
                    raise ValueError("Tool name and operation disagree")
                parameters["operation"] = name
                self._e6b_routed_aliases.append(name)
            response, reward, metrics = await tool.execute(self._rollout_id, parameters)
            if (metrics or {}).get("valid") is False:
                self._rollout_tool_errors.append(str(response.text))
            return response, 0.0 if reward is None else float(reward), metrics or {}
        except Exception as exc:
            self._rollout_tool_errors.append(str(exc))
            return ToolResponse(text=f"Error when executing tool: {exc}"), 0.0, {"error": str(exc)}

    async def _call_tool(self, tool_call, tools_kwargs):
        return await self._persistent_call_tool(tool_call)

    @staticmethod
    def _ground_truth(kwargs: Mapping[str, Any]) -> Mapping[str, Any]:
        reward_model = kwargs.get("reward_model")
        if isinstance(reward_model, Mapping):
            ground_truth = reward_model.get("ground_truth")
            if isinstance(ground_truth, Mapping):
                return ground_truth
        return {}

    @classmethod
    def _rollout_limit_reached(cls, agent_data: AgentData) -> bool:
        return bool(
            len(agent_data.response_mask) >= cls.response_length
            or (cls.max_assistant_turns and agent_data.assistant_turns >= cls.max_assistant_turns)
            or (cls.max_user_turns and agent_data.user_turns >= cls.max_user_turns)
        )

    @staticmethod
    def _looks_like_report(text: str) -> bool:
        if len(text.strip()) < 200:
            return False
        report_markers = (
            len(re.findall(r"^#{1,4}\s+\S", text, re.MULTILINE)) >= 1
            or bool(re.search(r"(?:references?|sources?|参考文献|参考资料|结论|总结)", text, re.IGNORECASE))
        )
        return report_markers

    @classmethod
    def _last_terminal_report(cls, agent_data: AgentData) -> tuple[str, str]:
        """Recover only an explicit/direct final report from the last response."""

        raw = cls.tokenizer.decode(agent_data.response_ids, skip_special_tokens=False).strip()
        if "submit_report" in raw and "<tool_call>" in raw:
            match = re.search(r'"content"\s*:\s*"', raw)
            if match:
                tail = raw[match.end() :]
                end = tail.rfind('"')
                if end > 0:
                    candidate = tail[:end]
                    try:
                        candidate = json.loads(f'"{candidate}"')
                    except json.JSONDecodeError:
                        candidate = (
                            candidate.replace("\\n", "\n")
                            .replace("\\t", "\t")
                            .replace('\\"', '"')
                            .replace("\\\\", "\\")
                        )
                    if cls._looks_like_report(candidate):
                        return candidate.strip(), "repaired_submit_terminal"

        text = cls.tokenizer.decode(agent_data.response_ids, skip_special_tokens=True).strip()
        if (
            not text
            or "<tool_call>" in text
            or re.search(r'"(?:name|operation)"\s*:\s*"(?:cosight_step|\w+_evidence|\w+_plan)', text)
        ):
            return "", ""
        if cls._looks_like_report(text):
            return text, "direct_markdown_terminal"
        return "", ""

    @rollout_trace_op
    async def run(self, sampling_params: dict[str, Any], **kwargs) -> AgentLoopOutput:
        messages = list(kwargs["raw_prompt"])
        image_data = copy.deepcopy(kwargs.get("multi_modal_data", {}).get("image", None))
        request_id = uuid4().hex
        self._rollout_id = request_id
        self._rollout_tool_errors: list[str] = []
        guided_capture = os.getenv("COSIGHT_E6B_GUIDED") == "1"
        self._e6b_routed_aliases: list[str] = []
        termination = "generation_end"
        ground_truth = self._ground_truth(kwargs)
        extra_info = kwargs.get("extra_info") if isinstance(kwargs.get("extra_info"), Mapping) else {}
        raw_image_rollout_disabled = bool(
            ground_truth.get("visual_input_mode") == "frozen_observation"
            or extra_info.get("raw_image_rollout_disabled")
        )
        if raw_image_rollout_disabled and image_data:
            raise ValueError(
                "Frozen-observation rollout received raw multi_modal_data. Rebuild the parquet "
                "without --skip-prepare so vLLM does not execute the incompatible visual tower."
            )
        rubric = ground_truth.get("rubric") or extra_info.get("rubric")
        local_evidence = ground_truth.get("local_evidence") or extra_info.get("local_evidence") or []
        task_id = extra_info.get("qid") or extra_info.get("task_id") or kwargs.get("index") or request_id

        workspace_tool = self.tools["cosight_step"]
        await workspace_tool.create(
            instance_id=request_id,
            create_kwargs={
                "task_id": task_id,
                "rubric": rubric,
                "local_evidence": local_evidence,
            },
        )

        agent_data = AgentData(
            messages=messages,
            image_data=image_data,
            metrics={},
            request_id=request_id,
            tools_kwargs={},
        )
        state = AgentState.PENDING
        while state != AgentState.TERMINATED:
            if state == AgentState.PENDING:
                state = await self._handle_pending_state(agent_data, sampling_params)
            elif state == AgentState.GENERATING:
                # Parse and execute a tool call emitted on the final allowed
                # turn. The upstream loop checks limits before parsing, which
                # used to discard a valid last-turn submit_report action.
                state = await self._handle_generating_state(
                    agent_data,
                    sampling_params,
                    ignore_termination=True,
                )
                if state == AgentState.TERMINATED and self._rollout_limit_reached(agent_data):
                    termination = "trajectory_budget"
                    if guided_capture and len(agent_data.response_mask) <= self.response_length:
                        # The base loop still checks turn limits before parsing when ignore_termination is set.
                        _, agent_data.tool_calls = await self.tool_parser.extract_tool_calls(agent_data.response_ids)
                        if agent_data.tool_calls:
                            state = AgentState.PROCESSING_TOOLS
            elif state == AgentState.PROCESSING_TOOLS:
                state = await self._handle_processing_tools_state(agent_data)
                if workspace_tool.is_submitted(request_id):
                    termination = "explicit_submission"
                    state = AgentState.TERMINATED
                elif state == AgentState.TERMINATED:
                    termination = "tool_response_budget"
                elif self._rollout_limit_reached(agent_data):
                    termination = "trajectory_budget"
                    state = AgentState.TERMINATED
            else:
                state = AgentState.TERMINATED

        # Dimension-only GRPO still scores only the final report. This fallback
        # changes no reward weights: it merely recognizes a report already
        # generated by the policy when the episode ended through a direct final
        # answer or an early submit_report blocked by workflow bookkeeping.
        if (
            rubric_schema(rubric) == DIMENSION_SCHEMA_VERSION
            and "step_rubric" not in ground_truth
            and not workspace_tool.is_submitted(request_id)
        ):
            terminal_report, terminal_mode = self._last_terminal_report(agent_data)
            if terminal_report:
                workspace_tool.promote_report_candidate(
                    request_id,
                    terminal_report,
                    mode=terminal_mode,
                )
            elif workspace_tool.promote_report_candidate(
                request_id,
                mode="incomplete_workflow_terminal",
            ):
                pass

        response_ids = agent_data.prompt_ids[-len(agent_data.response_mask) :]
        prompt_ids = agent_data.prompt_ids[: len(agent_data.prompt_ids) - len(agent_data.response_mask)]
        workspace_state = workspace_tool.snapshot(request_id)
        # Count failures in this sampled rollout, never in a teacher prefix.
        workspace_state["tool_errors"] = list(self._rollout_tool_errors)
        reward = score_trajectory(
            ground_truth,
            trajectory_state=workspace_state,
            extra_info=extra_info,
        )
        reward_extra_info = {}
        if os.getenv("COSIGHT_E6A_SHADOW") == "1":
            if reward.get("reward_mode") != "joint_trajectory" or os.getenv("COSIGHT_ENABLE_SOURCE_PROVENANCE", "1") != "1":
                raise ValueError("E6a rollout preflight requires the source-on joint trajectory reward")
            alternate = score_trajectory(ground_truth, workspace_state, extra_info, enable_source_provenance=False)
            if reward["step_reward"] != alternate["step_reward"]:
                raise RuntimeError("The E6a source switch changed the process reward")
            reward_extra_info = {
                "e6a_qid": str(extra_info["qid"]),
                "e6a_source_on": reward["score"],
                "e6a_source_off": alternate["score"],
                "e6a_report_on": reward["report_reward"]["score"],
                "e6a_report_off": alternate["report_reward"]["score"],
                "e6a_cap_on": reward["report_reward"]["reward_cap"],
                "e6a_cap_off": alternate["report_reward"]["reward_cap"],
                "e6a_step": reward["step_reward"]["score"],
                "e6a_report_submitted": float(reward["submitted_report"]),
            }
        if os.getenv("COSIGHT_E6B_CAPTURE") == "1":
            if not kwargs.get("uid"):
                raise ValueError("E6b capture requires a validation prompt group UID")
            state_fields = ("plan", "completed_steps", "searches", "events", "submitted_report", "last_report_candidate",
                            "report_submission_mode", "invalid_dependency_attempts", "tool_errors")
            reward_extra_info.update(
                e6b_qid=str(task_id),
                e6b_group_id=str(kwargs["uid"]),
                e6b_sample_id=request_id,
                e6b_state=json.dumps({**{key: workspace_state[key] for key in state_fields},
                                      "capture_diagnostics": {"assistant_turns": agent_data.assistant_turns,
                                                              "user_turns": agent_data.user_turns,
                                                              "response_tokens": len(agent_data.response_mask),
                                                              "termination": termination,
                                                              "routed_aliases": self._e6b_routed_aliases}}, ensure_ascii=False),
            )
        await workspace_tool.cleanup(request_id)

        report_submitted = bool(workspace_state.get("submitted_report"))
        submission_mode = str(workspace_state.get("report_submission_mode") or "")
        agent_data.metrics.update(
            {
                "cosight_plan_created": float(bool((workspace_state.get("plan") or {}).get("steps"))),
                "cosight_completed_steps": float(len(workspace_state.get("completed_steps") or [])),
                "cosight_searches": float(len(workspace_state.get("searches") or [])),
                "cosight_report_submitted": float(report_submitted),
                "cosight_report_fallback": float(
                    submission_mode
                    in {
                        "direct_markdown_terminal",
                        "repaired_submit_terminal",
                        "incomplete_workflow_terminal",
                    }
                ),
                "cosight_missing_report_reward": float(
                    reward.get("error") == "missing_submitted_report"
                ),
            }
        )

        multi_modal_data = {"image": agent_data.image_data} if agent_data.image_data is not None else {}
        output = AgentLoopOutput(
            prompt_ids=prompt_ids,
            response_ids=response_ids[: self.response_length],
            response_mask=agent_data.response_mask[: self.response_length],
            multi_modal_data=multi_modal_data,
            response_logprobs=agent_data.response_logprobs[: self.response_length]
            if agent_data.response_logprobs
            else None,
            reward_score=float(reward["score"]),
            num_turns=agent_data.user_turns + agent_data.assistant_turns + 1,
            metrics=agent_data.metrics,
            extra_fields={
                "trajectory_reward": reward,
                "reward_extra_info": reward_extra_info,
                "trajectory_summary": {
                    "task_id": str(task_id),
                    "plan_steps": len((workspace_state.get("plan") or {}).get("steps") or []),
                    "completed_steps": len(workspace_state.get("completed_steps") or []),
                    "searches": len(workspace_state.get("searches") or []),
                    "report_submitted": report_submitted,
                    "report_submission_mode": submission_mode,
                    "reward_error": str(reward.get("error") or ""),
                },
            },
        )
        return output


__all__ = ["CoSightPlanActAgentLoop"]
